/**
 * Auto-fetch script for landing page stats.
 *
 * Pulls live numbers at build time:
 *   - GitHub stars across the w3-kit org
 *   - npm weekly downloads summed across published packages
 * (Counts of components, chains and tokens come from the site's own data.)
 *
 * A number is null when its request fails, so dev/build keeps working offline
 * and the page can leave it out rather than show a wrong value.
 * Writes to src/entities/stats/model/stats.gen.ts.
 *
 * Run: npx tsx scripts/generate-stats.ts
 * Wired into: "prebuild" and "predev" npm scripts (via "generate")
 */

import fs from "node:fs";
import path from "node:path";

const WEBSITE_ROOT = path.resolve(import.meta.dirname, "..");
const OUT_FILE = path.resolve(import.meta.dirname, "../src/entities/stats/model/stats.gen.ts");

// ── Sources ─────────────────────────────────────────────────────────────────

// Repos under the w3-kit org we want to sum stars across.
const GH_REPOS = [
  "w3-kit/website",
  "w3-kit/ui",
  "w3-kit/cli",
  "w3-kit/registry",
  "w3-kit/learn",
  "w3-kit/contracts",
  "w3-kit/config",
  "w3-kit/bot",
];

// Published npm packages we want to sum weekly downloads across.
const NPM_PACKAGES = ["w3-kit", "@w3-kit/registry", "@w3-kit/config", "@w3-kit/mcp"];

// ── Helpers ─────────────────────────────────────────────────────────────────

async function fetchJson<T>(url: string, headers: Record<string, string> = {}): Promise<T | null> {
  try {
    const res = await fetch(url, {
      headers: { "User-Agent": "w3-kit-website-stats", ...headers },
    });
    if (!res.ok) return null;
    return (await res.json()) as T;
  } catch {
    return null;
  }
}

// ── Fetchers ────────────────────────────────────────────────────────────────

async function fetchGithubStars(): Promise<number> {
  const headers: Record<string, string> = {};
  const token = process.env.GITHUB_TOKEN;
  if (token) headers.Authorization = `Bearer ${token}`;

  const results = await Promise.all(
    GH_REPOS.map(async (repo) => {
      const data = await fetchJson<{ stargazers_count?: number }>(
        `https://api.github.com/repos/${repo}`,
        headers,
      );
      return data?.stargazers_count ?? 0;
    }),
  );
  return results.reduce((a, b) => a + b, 0);
}

async function fetchNpmWeeklyDownloads(): Promise<number> {
  const results = await Promise.all(
    NPM_PACKAGES.map(async (pkg) => {
      const data = await fetchJson<{ downloads?: number }>(
        `https://api.npmjs.org/downloads/point/last-week/${encodeURIComponent(pkg)}`,
      );
      return data?.downloads ?? 0;
    }),
  );
  return results.reduce((a, b) => a + b, 0);
}

// ── Run ─────────────────────────────────────────────────────────────────────

async function main() {
  console.log("Fetching landing stats...");

  const [stars, npmWeekly] = await Promise.all([fetchGithubStars(), fetchNpmWeeklyDownloads()]);
  console.log(`  GitHub stars (org sum): ${stars}`);
  console.log(`  npm downloads / week:   ${npmWeekly}`);

  const content = `/* AUTO-GENERATED by scripts/generate-stats.ts — do not edit by hand. */

export const STATS_GENERATED_AT = "${new Date().toISOString()}";

/** null when the fetch failed at build time. */
export const FETCHED_STATS: { githubStars: number | null; npmWeeklyDownloads: number | null } = {
  githubStars: ${stars > 0 ? stars : "null"},
  npmWeeklyDownloads: ${npmWeekly > 0 ? npmWeekly : "null"},
};
`;

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, content);
  console.log(`  Wrote ${path.relative(WEBSITE_ROOT, OUT_FILE)}`);
  console.log("Done!");
}

main().catch((err) => {
  console.error("generate-stats failed:", err);
  process.exit(0); // never fail the build over a stats fetch
});
